#!/usr/bin/env python
"""Derive paper_b/refs.bib from the master refs/refs.bib, fit for submission.

The master library carries a `note` field on most entries holding our reading notes. Those are
valuable there and must never reach a submitted bibliography, so this strips them. It also
rewrites author names of the form "Heath, Robert W., Jr." into BibTeX's three-part
"Last, Jr, First" form, which otherwise renders as "J. Heath, Robert W.".

Regenerate whenever refs/refs.bib changes. Usage: python experiments/make_paper_b_bib.py
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "refs", "refs.bib")
DST = os.path.join(ROOT, "paper_b", "refs.bib")


def strip_notes(text):
    """Remove a top-level `note = {...}` field, honoring nested braces."""
    out, i, removed = [], 0, 0
    while True:
        m = re.compile(r"\n\s*note\s*=\s*\{", re.I).search(text, i)
        if not m:
            out.append(text[i:]); break
        out.append(text[i:m.start()])
        j, depth = m.end(), 1
        while j < len(text) and depth:
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
            j += 1
        while j < len(text) and text[j] in " ,\t":
            j += 1
        if j < len(text) and text[j] == "\n":
            pass
        i = j
        removed += 1
    return "".join(out), removed


def fix_jr(text):
    """"Heath, Robert W., Jr." -> "Heath, Jr., Robert W." (BibTeX Last, Jr, First)."""
    n = [0]

    def rep(m):
        n[0] += 1
        return f"{m.group(1)}, Jr., {m.group(2)}"

    # Applied to the whole file rather than per field. A per-field regex cannot be written
    # with a lazy (.*?) because accented names such as Gonz{\'a}lez contain braces, which
    # truncate the field; and "Last, First, Jr." occurs only in author lists anyway, since
    # the note fields holding prose have already been stripped.
    text = re.sub(r"([A-Z][A-Za-z'\-]+),\s*([^,{}]+?),\s*Jr\.", rep, text)
    return text, n[0]


# IEEE style abbreviates periodical titles. The master library stores them in full, which is
# right for a reading library and wrong for an IEEE submission, so they are abbreviated here.
# Longest-first so that "IEEE Transactions on Signal Processing" is not shortened by the
# "IEEE Transactions on Signal" prefix of nothing, and so substrings cannot pre-empt wholes.
JOURNAL_ABBREV = {
    "IEEE Journal of Selected Topics in Signal Processing": "IEEE J. Sel. Topics Signal Process.",
    "IEEE Journal on Selected Areas in Communications": "IEEE J. Sel. Areas Commun.",
    "IEEE Transactions on Wireless Communications": "IEEE Trans. Wireless Commun.",
    "IEEE Transactions on Vehicular Technology": "IEEE Trans. Veh. Technol.",
    "IEEE Transactions on Signal Processing": "IEEE Trans. Signal Process.",
    "IEEE Transactions on Communications": "IEEE Trans. Commun.",
    "IEEE Communications Surveys and Tutorials": "IEEE Commun. Surveys Tuts.",
    "IEEE Wireless Communications Letters": "IEEE Wireless Commun. Lett.",
    "IEEE Signal Processing Magazine": "IEEE Signal Process. Mag.",
    "IEEE Communications Magazine": "IEEE Commun. Mag.",
    "IEEE Transactions on Information Theory": "IEEE Trans. Inf. Theory",
    "IEEE Transactions on Image Processing": "IEEE Trans. Image Process.",
    "IEEE Transactions on Medical Imaging": "IEEE Trans. Med. Imag.",
    "IEEE Access": "IEEE Access",
    "IEEE Network": "IEEE Netw.",
    "IET Radar, Sonar and Navigation": "IET Radar Sonar Navig.",
    "Proceedings of the National Academy of Sciences": "Proc. Nat. Acad. Sci.",
    "Nature Methods": "Nature Methods",
    "Nature Machine Intelligence": "Nature Mach. Intell.",
    "Psychological Methods": "Psychol. Methods",
    "Journal of Machine Learning Research": "J. Mach. Learn. Res.",
    "International Journal of Computer Vision": "Int. J. Comput. Vis.",
}


def abbrev_journals(text):
    n = 0
    for full, short in sorted(JOURNAL_ABBREV.items(), key=lambda kv: -len(kv[0])):
        if full == short:
            continue
        c = text.count(full)
        if c:
            text = text.replace(full, short)
            n += c
    return text, n


def main():
    src = open(SRC).read()
    txt, nnotes = strip_notes(src)
    txt, njr = fix_jr(txt)
    txt, nabb = abbrev_journals(txt)
    hdr = ("% Generated by experiments/make_paper_b_bib.py from refs/refs.bib.\n"
           "% Do not edit. Reading notes are stripped and 'Jr.' names are put into\n"
           "% BibTeX's three-part Last, Jr, First form.\n")
    open(DST, "w").write(hdr + txt)
    nent = len(re.findall(r"^@", txt, re.M))
    # Check field content only: the source file's own header comments mention VERIFIED.
    noncomment = "\n".join(l for l in txt.splitlines() if not l.lstrip().startswith("%"))
    assert "note" not in re.sub(r"[^a-z=]", "", noncomment.lower()).replace("notes", ""), \
        "a note field survived"
    for probe in ("VERIFIED", "our checklist", "do not cite"):
        assert probe not in noncomment, f"a reading note survived: {probe!r}"
    print(f"wrote {DST}: {nent} entries, {nnotes} note fields stripped, {njr} names fixed, "
          f"{nabb} journal titles abbreviated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
